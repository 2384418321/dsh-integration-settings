// Build both halves of the plugin:
//   src/index.js   -> lib/index.js    (host / Node ESM, everything bundled)
//   src/client.jsx -> lib/client.js   (browser CJS inside window.__ModuleLoader__.load)
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const pkgName = 'dsh-integration-settings'
// DSI_DEBUG=1 ships an unminified client bundle with intact function names plus
// an inline source map, so a browser stack trace names the real component and
// line instead of a mangled symbol. Never use it for a release build.
const debug = process.env.DSI_DEBUG === '1'

const shared = {
  absWorkingDir: root,
  bundle: true,
  sourcemap: false,
  logLevel: 'info',
  define: { 'process.env.NODE_ENV': '"production"' },
}

await build({
  ...shared,
  entryPoints: ['src/index.js'],
  outfile: 'lib/index.js',
  format: 'esm',
  platform: 'node',
  target: 'node20',
  minify: false,
  // Bundled CommonJS dependencies (yaml) call require('process'); in real ESM
  // esbuild's __require shim only delegates when a `require` exists, so provide
  // one via createRequire.
  banner: {
    js:
      '// generated by scripts/build.mjs - do not edit\n' +
      "import { createRequire as __dsiCreateRequire } from 'node:module';\n" +
      'const require = __dsiCreateRequire(import.meta.url);',
  },
})

await build({
  ...shared,
  entryPoints: ['src/client.jsx'],
  outfile: 'lib/client.js',
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  minify: !debug,
  keepNames: debug,
  sourcemap: debug ? 'inline' : false,
  jsx: 'transform',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'],
  banner: {
    js:
      `window.__ModuleLoader__.load({ id: "${pkgName}", factory: (require) => {\n` +
      'var module = { exports: {} };\nvar exports = module.exports;',
  },
  footer: { js: 'return module.exports;\n} });' },
})

console.log('[build] lib/index.js + lib/client.js written')
